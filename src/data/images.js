export function resolveProductImage(url) {
  if (!url) return null;

  const match = url.match(/\/tienda\/([^/?#]+)/);
  if (!match) return null;

  const slug = match[1];
  const filename = IMAGE_MAP[slug];

  if (!filename) return null;
  return LOCAL_IMAGES[filename] || null;
}
