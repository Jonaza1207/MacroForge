// Load ALL image formats automatically — no manual mapping needed
const _mods = import.meta.glob(
  '../assets/products/**/*.{png,jpg,jpeg,webp,PNG,JPG,JPEG,WEBP}',
  { eager: true }
);

// Strip all non-alphanumeric for fuzzy filename→product matching
export const _strip = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');

// LOCAL_IMAGES: stripped-filename-key → resolved URL (fully auto-discovered)
export const LOCAL_IMAGES = {};
for (const [path, mod] of Object.entries(_mods)) {
  const filename = path.split('/').pop().replace(/\.[^.]+$/, '');
  LOCAL_IMAGES[_strip(filename)] = mod.default;
}

// Case-insensitive lookup inside LOCAL_IMAGES (handles mixed-case filenames)
function _find(filename) {
  return LOCAL_IMAGES[_strip(filename)] ?? null;
}

