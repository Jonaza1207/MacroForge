// Resolve a product image from local PNGs only.
// slug → _map → LOCAL_IMAGES → hashed PNG URL, or null.
// No CDN fallback. No fuzzy matching. Deterministic.
export function resolveProductImage(url) {
  const m = url?.match(/\/tienda\/([^/?#]+)/);
  if (!m) return null;
  const filename = _map[m[1]];
  return filename ? _find(filename) : null;
}
